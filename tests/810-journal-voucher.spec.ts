// ─────────────────────────────────────────────────────────────────────────
// Manual journal voucher on the TEST BU (GR2VYNKQ): create, submit + approve (post), void, reverse, and the rule that a
// subledger JV (AP, generated by posting an AP document) cannot be voided or reversed directly.
//
// Workflow `gl_jv` covers manual sources only (Create Request -> Accounting Approval -> Completed): Admin creates and
// submits, Budget approves and the approval posts. Budget also sits on the create stage, so it can approve its own
// JV. The JV oracle (general-ledger-journal-voucher-design.md) states no maker-checker rule (only "403 - wrong workflow
// stage", jv:283), so that is NOT pinned, unlike AP payment 804 TC-APAPR-030001. Requestor is the view-only role.
// Read set (never mutated): E2E-JV-POSTED (Dr 5300 250.00 / Cr 1110 250.00, posted). Every state-changing case creates its
// own tagged JV, so the spec re-runs without a reset.
//
// Oracle points: reverse = posted manual JV only, creates a linked mirror JV with sides swapped (jv:247, jv:221-222);
// void "keeps a reason" (jv:246, the doc does not say the reason is required: the BE refuses a missing one, asserted
// as observed behaviour); AP/AR/inventory JVs are immutable projections, corrected from the source owner (jv:315).
// Divergence from jv:241 is pinned `test.fail` with "needs product decision:" (bug list section 2). Owner 2026-11-23: void is for posted JVs only; a draft is deleted instead (TC-JV-040004/040005).
// Auto-reverse (jv:300) and Schedule Post run from a scheduler, not on demand: out of scope, no case.
// ─────────────────────────────────────────────────────────────────────────
