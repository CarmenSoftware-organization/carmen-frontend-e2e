type Row = Record<string, any>;

async function getJv(id: string): Promise<Row> {
  const r = await buSend(CREATOR, "GET", `/gl-jv/${id}`);
  expect(r.status).toBe(200);
  return r.body.data as Row;
}

/** The JV a UI save created, found by its tagged description. */
async function jvByTag(t: string): Promise<Row | undefined> {
  return (await listAllRows(CREATOR, `/gl-jv?search=${encodeURIComponent(t)}`)).find((j) => j.description === t);
}

/** A manual JV that went draft -> in_review (Admin) -> posted (Budget). */
async function postedJv(key: string): Promise<{ id: string; no: string }> {
  const jv = await createManualJv(BALANCED, tag(key));
  expect((await submitJv(jv.id)).status).toBe(200);
  expect((await approveJv(jv.id)).status).toBe(200);
  expect((await getJv(jv.id)).jv_status).toBe("posted");
  return jv;
}

const lineSummary = (d: Row) =>
  (d.tb_gl_jv_detail as Row[]).map((l) => ({ account: String(l.account_code), dr: Number(l.debit), cr: Number(l.credit) }));

/** `YYYY-MM-DD` of the day after `day` (calendar arithmetic on UTC, no local clock). */
function nextDay(day: string): string {
  const d = new Date(`${day}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + 1);
  return d.toISOString().slice(0, 10);
}

